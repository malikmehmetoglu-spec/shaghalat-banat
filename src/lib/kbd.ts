/**
 * قارئ الباركود يكتب كلوحة مفاتيح: إن كانت لغة Windows عربية تتحول الأحرف الإنجليزية إلى عربية.
 * نعيدها دائماً إلى ما يقابلها في لوحة المفاتيح الإنجليزية، ونحوّل الأرقام العربية إلى إنجليزية.
 */
const AR: Record<string, string> = {
  "ض": "q", "ص": "w", "ث": "e", "ق": "r", "ف": "t", "غ": "y", "ع": "u", "ه": "i", "خ": "o", "ح": "p", "ج": "[", "د": "]",
  "ش": "a", "س": "s", "ي": "d", "ب": "f", "ل": "g", "ا": "h", "ت": "j", "ن": "k", "م": "l", "ك": ";", "ط": "'",
  "ئ": "z", "ء": "x", "ؤ": "c", "ر": "v", "ى": "n", "ة": "m", "و": ",", "ز": ".", "ظ": "/", "ذ": "`",
  "لا": "b", "لآ": "B", "لأ": "G", "لإ": "T", "أ": "H", "إ": "Y", "آ": "N", "ـ": "J", "،": "K", "/": "L", "؛": "P", "'": "O",
};
export function toEnglishKeys(s: string): string {
  return s
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x660))
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x6f0))
    .replace(/لا|لآ|لأ|لإ/g, (m) => AR[m])
    .replace(/[؀-ۿ]/g, (c) => AR[c] ?? c);
}
